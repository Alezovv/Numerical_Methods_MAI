import numpy as np

print("--- Поиск комплексно-сопряженных собственных значений (NumPy) ---")

# Собственный пример матрицы (матрица поворота с масштабированием)
# Такая матрица гарантированно имеет комплексные собственные значения
A = np.array([
    [2.0, -3.0,  0.0],
    [3.0,  2.0,  0.0],
    [0.0,  0.0,  5.0]
])

print("\nИсходная матрица A:")
print(A)

# Нахождение собственных значений с помощью встроенной функции (алгоритм QR под капотом)
eigenvalues, eigenvectors = np.linalg.eig(A)

print("\nНайденные собственные значения:")
for i, val in enumerate(eigenvalues):
    print(f"Lambda_{i+1} = {val:.4f}")

print("\nКак мы видим, присутствуют комплексно-сопряженные корни:")
print(f"{eigenvalues[0]:.4f} и {eigenvalues[1]:.4f}")
